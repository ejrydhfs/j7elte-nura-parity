import json, subprocess, sys, os, base64
env=dict(os.environ, OPENCAMO_URL="http://192.168.0.8:47777")
p=subprocess.Popen([sys.executable,"mcp/opencamo_mcp.py"],stdin=subprocess.PIPE,stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True,bufsize=1,env=env)
def send(o): p.stdin.write(json.dumps(o)+"\n"); p.stdin.flush()
def call(i, name, args):
    send({"jsonrpc":"2.0","id":i,"method":"tools/call","params":{"name":name,"arguments":args}})
    return json.loads(p.stdout.readline())
send({"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-06-18","capabilities":{},"clientInfo":{"name":"p","version":"0"}}})
p.stdout.readline()
send({"jsonrpc":"2.0","method":"notifications/initialized"})
send({"jsonrpc":"2.0","id":2,"method":"tools/list"}); tools=json.loads(p.stdout.readline())
print("tools:", [t["name"] for t in tools["result"]["tools"]])
r=call(3,"select_camera",{"camera":"back","width":1920,"height":1080,"fps":30}); print("select_camera:", r["result"]["content"][0]["text"].replace("\n"," ")[:120])
r=call(4,"focus_position",{"percent":50,"camera":"back"}); print("focus_position:", r["result"]["content"][0]["text"].replace("\n"," ")[:140])
r=call(5,"snapshot",{"camera":"back","grid":True,"max_width":640,"width":1920,"height":1080}); print("snapshot:", [c["type"] for c in r["result"]["content"]], "b64len", len([c for c in r["result"]["content"] if c["type"]=="image"][0]["data"]))
r=call(6,"focus",{"x":0.3,"y":0.7}); print("focus:", r["result"]["content"][0]["text"].replace("\n"," ")[:120])
r=call(7,"status",{}); print("status:", r["result"]["content"][0]["text"].replace("\n"," ")[:160])
p.stdin.close(); p.wait(timeout=10)
