import json, subprocess, sys, os
env=dict(os.environ, OPENCAMO_URL="http://192.168.0.8:47777")
p=subprocess.Popen([sys.executable,"mcp/opencamo_mcp.py"],stdin=subprocess.PIPE,stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True,bufsize=1,env=env)
def send(o): p.stdin.write(json.dumps(o)+"\n"); p.stdin.flush()
def call(i,name,args):
    send({"jsonrpc":"2.0","id":i,"method":"tools/call","params":{"name":name,"arguments":args}})
    return json.loads(p.stdout.readline())["result"]["content"][0]["text"].replace("\n"," ")
send({"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-06-18","capabilities":{},"clientInfo":{"name":"p","version":"0"}}})
p.stdout.readline(); send({"jsonrpc":"2.0","method":"notifications/initialized"})
send({"jsonrpc":"2.0","id":2,"method":"tools/list"}); t=json.loads(p.stdout.readline())
print("tools:", len(t["result"]["tools"]), [x["name"] for x in t["result"]["tools"]])
print("exposure(ev=1.5):", call(3,"exposure",{"ev":1.5})[:150])
print("exposure_manual:", call(4,"exposure_manual",{"iso":800,"shutter_ns":15000000})[:170])
print("metering(highlight):", call(5,"metering",{"mode":"highlight"})[:150])
print("exposure_auto:", call(6,"exposure_auto",{})[:150])
print("focus_lock(1):", call(7,"focus_lock",{"on":True})[:120])
print("focus_policy(implicit):", call(8,"focus_policy",{"policy":"implicit"})[:120])
p.stdin.close(); p.wait(timeout=10)
print("stderr:", p.stderr.read()[:150])
